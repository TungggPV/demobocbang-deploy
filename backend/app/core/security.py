"""Password and compact signed-token primitives for authentication."""

import base64
import hashlib
import hmac
import json
import secrets
from datetime import UTC, datetime, timedelta
from typing import Any
from uuid import UUID, uuid4

from app.core.errors import ApiError

_SCRYPT_N = 2**14
_SCRYPT_R = 8
_SCRYPT_P = 1


def hash_secret(value: str) -> str:
    """Hash a password or OTP without retaining plaintext or a reusable salt."""
    salt = secrets.token_bytes(16)
    derived = hashlib.scrypt(
        value.encode("utf-8"), salt=salt, n=_SCRYPT_N, r=_SCRYPT_R, p=_SCRYPT_P
    )
    return "$".join(
        (
            "scrypt",
            str(_SCRYPT_N),
            str(_SCRYPT_R),
            str(_SCRYPT_P),
            _b64encode(salt),
            _b64encode(derived),
        )
    )


def verify_secret(value: str, encoded: str) -> bool:
    """Compare a supplied secret against the format generated by hash_secret."""
    try:
        algorithm, n, r, p, encoded_salt, expected = encoded.split("$")
        if algorithm != "scrypt":
            return False
        salt = _b64decode(encoded_salt)
        derived = hashlib.scrypt(
            value.encode("utf-8"), salt=salt, n=int(n), r=int(r), p=int(p)
        )
        return hmac.compare_digest(derived, _b64decode(expected))
    except (TypeError, ValueError):
        return False


def generate_otp() -> str:
    """Generate a six-digit OTP; the raw value is never persisted."""
    return f"{secrets.randbelow(1_000_000):06d}"


class TokenService:
    """Small, dependency-free HS256 JWT issuer and verifier."""

    def __init__(self, secret: str | None, access_ttl: int, refresh_ttl: int) -> None:
        self._secret = secret.encode("utf-8") if secret else None
        self._access_ttl = access_ttl
        self._refresh_ttl = refresh_ttl

    def issue_pair(self, user_id: UUID) -> tuple[str, str]:
        return (
            self._issue(user_id, "access", self._access_ttl),
            self._issue(user_id, "refresh", self._refresh_ttl),
        )

    def verify(self, token: str, expected_kind: str) -> UUID:
        payload = self._verify_payload(token, expected_kind)
        try:
            return UUID(payload["sub"])
        except (KeyError, TypeError, ValueError):
            raise ApiError("AUTH_REQUIRED", "Authentication is required.", 401) from None

    def issue_media_playback_ticket(self, user_id: UUID, meeting_id: UUID, media_id: UUID, ttl_seconds: int) -> str:
        """Issue a short-lived, media-scoped ticket rather than exposing an access token."""
        return self._issue(user_id, "media_playback", ttl_seconds, {"meeting_id": str(meeting_id), "media_id": str(media_id)})

    def verify_media_playback_ticket(self, token: str) -> tuple[UUID, UUID, UUID]:
        payload = self._verify_payload(token, "media_playback")
        try:
            return UUID(payload["sub"]), UUID(payload["meeting_id"]), UUID(payload["media_id"])
        except (KeyError, TypeError, ValueError):
            raise ApiError("AUTH_REQUIRED", "Authentication is required.", 401) from None

    def _verify_payload(self, token: str, expected_kind: str) -> dict[str, Any]:
        if self._secret is None:
            raise ApiError("AUTH_NOT_CONFIGURED", "Authentication is not configured.", 503)
        try:
            header_part, payload_part, signature_part = token.split(".")
            signed = f"{header_part}.{payload_part}".encode("ascii")
            expected_signature = hmac.new(self._secret, signed, hashlib.sha256).digest()
            if not hmac.compare_digest(expected_signature, _b64decode(signature_part)):
                raise ValueError("signature")
            header = json.loads(_b64decode(header_part))
            payload = json.loads(_b64decode(payload_part))
            if header != {"alg": "HS256", "typ": "JWT"}:
                raise ValueError("header")
            if payload["kind"] != expected_kind or int(payload["exp"]) <= int(_now().timestamp()):
                raise ValueError("claims")
            return payload
        except (KeyError, TypeError, ValueError, json.JSONDecodeError):
            raise ApiError("AUTH_REQUIRED", "Authentication is required.", 401) from None

    def issue_oauth_state(self, extra: dict[str, str] | None = None) -> str:
        return self._issue(UUID(int=0), "google_oauth_state", 600, extra=extra)

    def verify_oauth_state(self, state: str) -> dict[str, Any]:
        return self._verify_payload(state, "google_oauth_state")

    def _issue(self, user_id: UUID, kind: str, ttl_seconds: int, extra: dict[str, str] | None = None) -> str:
        if self._secret is None:
            raise ApiError("AUTH_NOT_CONFIGURED", "Authentication is not configured.", 503)
        now = _now()
        header = _b64encode(
            json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode()
        )
        payload = _b64encode(
            json.dumps(
                {
                    "sub": str(user_id),
                    "kind": kind,
                    "iat": int(now.timestamp()),
                    "exp": int((now + timedelta(seconds=ttl_seconds)).timestamp()),
                    "jti": str(uuid4()),
                    **(extra or {}),
                },
                separators=(",", ":"),
            ).encode()
        )
        signature = _b64encode(
            hmac.new(self._secret, f"{header}.{payload}".encode(), hashlib.sha256).digest()
        )
        return f"{header}.{payload}.{signature}"


def _now() -> datetime:
    return datetime.now(UTC)


def _b64encode(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode("ascii")


def _b64decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
